'use client';

import { useState } from 'react';
import { Button } from '@/components/ui/button';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { Alert, AlertDescription, AlertTitle } from '@/components/ui/alert';
import { ClipboardList, Loader2, Printer, Sparkles, FileDown, CalendarCheck } from 'lucide-react';
import { useAppStore } from '@/lib/store';
import { Markdown } from './markdown';
import { toast } from '@/hooks/use-toast';

export function DoctorPrep() {
  const [prep, setPrep] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const [meta, setMeta] = useState<{ patientName: string; reportCount: number; withSymptoms: boolean } | null>(null);
  const { symptomTranscript } = useAppStore();

  const generate = async () => {
    setLoading(true);
    // 读取持久化的症状转录(跨页面/会话)
    let transcript = symptomTranscript;
    try {
      const stored = localStorage.getItem('vl_symptoms');
      if (stored) transcript = stored;
    } catch { /* ignore */ }
    try {
      const res = await fetch('/api/doctor-prep', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ symptomTranscript: transcript }),
      });
      const data = await res.json();
      if (!res.ok) throw new Error(data.error || 'Generation failed');
      setPrep(data.prep);
      setMeta({ patientName: data.patientName, reportCount: data.reportCount, withSymptoms: !!transcript });
    } catch (e: any) {
      toast({ title: 'Could not generate prep sheet', description: e.message, variant: 'destructive' });
    } finally {
      setLoading(false);
    }
  };

  const download = () => {
    if (!prep) return;
    const html = `<!DOCTYPE html><html><head><meta charset="utf-8"><title>VitalLens Visit Prep</title>
<style>
body{font-family:Georgia,serif;max-width:720px;margin:40px auto;padding:0 24px;color:#1a2b2b;line-height:1.6}
h1{color:#0f766e;border-bottom:2px solid #0f766e;padding-bottom:8px;font-size:22px}
h2{color:#0f766e;font-size:16px;margin-top:24px}
h3{color:#334155;font-size:14px;margin-top:18px}
table{border-collapse:collapse;width:100%;font-size:13px}
th,td{border:1px solid #cbd5d5;padding:6px 10px;text-align:left}
th{background:#f0fdfa}
ul{padding-left:20px}
.footer{margin-top:40px;font-size:11px;color:#888;border-top:1px solid #ddd;padding-top:8px}
</style></head><body>
<h1>🩺 VitalLens — Visit Prep Sheet</h1>
${markdownToHtml(prep)}
<p class="footer">Generated by VitalLens · Educational tool — not a medical record. Verify all values against official lab reports.</p>
</body></html>`;
    const blob = new Blob([html], { type: 'text/html' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `vitallens-visit-prep-${new Date().toISOString().slice(0, 10)}.html`;
    a.click();
    URL.revokeObjectURL(url);
    toast({ title: 'Prep sheet downloaded' });
  };

  return (
    <div className="mx-auto max-w-3xl space-y-5">
      <Card className="overflow-hidden">
        <CardContent className="relative p-6 sm:p-8">
          <div className="pointer-events-none absolute -right-10 -top-10 h-40 w-40 rounded-full bg-teal-100/60 blur-2xl" />
          <div className="flex flex-col items-start gap-4 sm:flex-row sm:items-center">
            <div className="rounded-2xl bg-gradient-to-br from-teal-500 to-emerald-600 p-4 shadow-lg shadow-teal-600/20">
              <ClipboardList className="h-8 w-8 text-white" />
            </div>
            <div className="flex-1">
              <h3 className="text-xl font-semibold">Walk in prepared, walk out with answers</h3>
              <p className="mt-1 text-sm text-muted-foreground">
                VitalLens combines your lab history{symptomTranscript ? ', symptom conversation' : ''} into a one-page
                visit prep sheet: what to say, what to show, and exactly what to ask.
              </p>
            </div>
          </div>
          <div className="mt-6 flex flex-wrap gap-3">
            <Button onClick={generate} disabled={loading} className="gap-2 bg-teal-700 hover:bg-teal-800">
              {loading ? <Loader2 className="h-4 w-4 animate-spin" /> : <Sparkles className="h-4 w-4" />}
              {loading ? 'Building your sheet…' : 'Generate visit prep sheet'}
            </Button>
            {prep && (
              <>
                <Button variant="outline" onClick={() => window.print()} className="gap-2"><Printer className="h-4 w-4" /> Print</Button>
                <Button variant="outline" onClick={download} className="gap-2"><FileDown className="h-4 w-4" /> Download</Button>
              </>
            )}
          </div>
          {meta && !loading && (
            <p className="mt-3 flex items-center gap-1.5 text-xs text-muted-foreground">
              <CalendarCheck className="h-3.5 w-3.5 text-teal-700" />
              Built from {meta.reportCount} lab report{meta.reportCount > 1 ? 's' : ''}{meta.withSymptoms ? ' + your symptom session' : ''} for {meta.patientName}.
            </p>
          )}
        </CardContent>
      </Card>

      {loading && (
        <Card>
          <CardContent className="space-y-3 p-6">
            <div className="flex items-center gap-2 text-sm text-muted-foreground"><Loader2 className="h-4 w-4 animate-spin text-teal-700" /> Dr. V is compiling your history…</div>
            <div className="h-3 w-3/4 animate-pulse rounded bg-muted" />
            <div className="h-3 w-full animate-pulse rounded bg-muted" />
            <div className="h-3 w-5/6 animate-pulse rounded bg-muted" />
            <div className="h-3 w-2/3 animate-pulse rounded bg-muted" />
          </CardContent>
        </Card>
      )}

      {prep && !loading && (
        <Card className="print:border-0 print:shadow-none">
          <CardHeader className="pb-3">
            <CardTitle className="text-base">Your visit prep sheet</CardTitle>
          </CardHeader>
          <CardContent>
            <Markdown content={prep} />
            <Alert className="mt-5 border-teal-200 bg-teal-50/50 print:hidden">
              <AlertTitle className="text-sm text-teal-900">Before your visit</AlertTitle>
              <AlertDescription className="text-xs text-muted-foreground">
                Bring your original lab reports too. This sheet summarizes values but the official documents remain the source of truth.
              </AlertDescription>
            </Alert>
          </CardContent>
        </Card>
      )}
    </div>
  );
}

// 简易 markdown -> html(用于下载)
function markdownToHtml(md: string): string {
  const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const lines = md.split('\n');
  let html = '';
  let inList = false;
  let inTable = false;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (line.startsWith('### ')) { if (inList) { html += '</ul>'; inList = false; } if (inTable) { html += '</table>'; inTable = false; } html += `<h3>${inline(esc(line.slice(4)))}</h3>`; continue; }
    if (line.startsWith('## ')) { if (inList) { html += '</ul>'; inList = false; } if (inTable) { html += '</table>'; inTable = false; } html += `<h2>${inline(esc(line.slice(3)))}</h2>`; continue; }
    if (line.startsWith('| ')) {
      const cells = line.split('|').slice(1, -1).map((c) => c.trim());
      if (cells.every((c) => /^-+$/.test(c.replace(/\s/g, '')) || c === '')) continue;
      if (!inTable) { if (inList) { html += '</ul>'; inList = false; } html += '<table>'; inTable = true; html += '<tr>' + cells.map((c) => `<th>${inline(esc(c))}</th>`).join('') + '</tr>'; continue; }
      html += '<tr>' + cells.map((c) => `<td>${inline(esc(c))}</td>`).join('') + '</tr>';
      continue;
    } else if (inTable) { html += '</table>'; inTable = false; }
    if (/^[-*•] /.test(line)) { if (!inList) { html += '<ul>'; inList = true; } html += `<li>${inline(esc(line.slice(2)))}</li>`; continue; }
    if (/^\d+\. /.test(line)) { if (!inList) { html += '<ul>'; inList = true; } html += `<li>${inline(esc(line.replace(/^\d+\. /, '')))}</li>`; continue; }
    if (inList && line.trim() === '') { html += '</ul>'; inList = false; continue; }
    if (line.trim() !== '') { if (inList) { html += '</ul>'; inList = false; } html += `<p>${inline(esc(line))}</p>`; }
  }
  if (inList) html += '</ul>';
  if (inTable) html += '</table>';
  return html;
}
function inline(s: string): string {
  return s.replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>').replace(/\*(.+?)\*/g, '<em>$1</em>');
}
